create table activities (
	id bigint generated by default as identity primary key,
	instructor_id bigint not null,
	title varchar(120) not null,
	problem_statement text not null,
	starter_code text not null default '',
	status varchar(16) not null,
	created_at timestamp with time zone not null,
	updated_at timestamp with time zone not null,
	constraint fk_activities_instructor foreign key (instructor_id) references users (id),
	constraint ck_activities_status check (status in ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

create index ix_activities_instructor_id on activities (instructor_id);

create index ix_activities_status on activities (status);

create table test_cases (
	id bigint generated by default as identity primary key,
	activity_id bigint not null,
	position int not null,
	input text not null default '',
	expected_output text not null,
	is_hidden boolean not null default false,
	constraint fk_test_cases_activity foreign key (activity_id) references activities (id) on delete cascade,
	constraint uk_test_cases_activity_position unique (activity_id, position)
);

create table sdi_configs (
	id bigint generated by default as identity primary key,
	activity_id bigint not null,
	threshold int not null,
	cooldown_seconds int not null,
	window_minutes int not null,
	constraint fk_sdi_configs_activity foreign key (activity_id) references activities (id) on delete cascade,
	constraint uk_sdi_configs_activity_id unique (activity_id),
	constraint ck_sdi_configs_threshold check (threshold between 0 and 100),
	constraint ck_sdi_configs_cooldown_seconds check (cooldown_seconds >= 0),
	constraint ck_sdi_configs_window_minutes check (window_minutes >= 1)
);
