create table coding_sessions (
	id bigint generated by default as identity primary key,
	student_id bigint not null,
	activity_id bigint not null,
	started_at timestamp with time zone not null,
	ended_at timestamp with time zone,
	peak_sdi int,
	runner_locked boolean not null default false,
	sdi_at_lock int,
	cooldown_ends_at timestamp with time zone,
	constraint fk_coding_sessions_student foreign key (student_id) references users (id),
	constraint fk_coding_sessions_activity foreign key (activity_id) references activities (id),
	constraint ck_coding_sessions_peak_sdi check (peak_sdi between 0 and 100),
	constraint ck_coding_sessions_sdi_at_lock check (sdi_at_lock between 0 and 100)
);

create index ix_coding_sessions_student_activity_started on coding_sessions (student_id, activity_id, started_at);

create table telemetry_events (
	id bigint generated by default as identity primary key,
	session_id bigint not null,
	client_event_id uuid not null,
	type varchar(8) not null,
	occurred_at timestamp with time zone not null,
	chars_added int,
	chars_removed int,
	passed_count int,
	total_count int,
	error_signature varchar(200),
	sdi_value int,
	constraint fk_telemetry_events_session foreign key (session_id) references coding_sessions (id),
	constraint uk_telemetry_events_session_client_event unique (session_id, client_event_id),
	constraint ck_telemetry_events_type check (type in ('EDIT', 'RUN', 'ERROR')),
	constraint ck_telemetry_events_sdi_value check (sdi_value between 0 and 100)
);

create index ix_telemetry_events_session_occurred on telemetry_events (session_id, occurred_at);

create table reflections (
	id bigint generated by default as identity primary key,
	session_id bigint not null,
	hypothesis text not null,
	planned_fix text not null,
	sdi_at_trigger int not null,
	submitted_at timestamp with time zone not null,
	constraint fk_reflections_session foreign key (session_id) references coding_sessions (id),
	constraint ck_reflections_sdi_at_trigger check (sdi_at_trigger between 0 and 100)
);

create index ix_reflections_session_id on reflections (session_id);
